stipend = float(input("Enter monthly stipend: "))

print("\n--- Name Analysis ---")
print("First 3 letters:", name[:3])
print("Uppercase name:", name.upper())


student_details = (name, age, course, employment, stipend)
print("\n========== STUDENT PROFILE ==========")
print(f"Name             : {name}")
print(f"Age              : {age}")
print(f"Course           : {course}")
print(f"Employment Status: {employment}")
print(f"Monthly Stipend  : ₹{stipend}")


marks = [85, 90, 75, 80, 90]

print("\n--- Marks Management ---")
print("Original marks:", marks)


marks.append(95)
print("After adding:", marks)


marks.remove(75)
print("After removing:", marks)


marks.sort()
print("Sorted marks:", marks)


unique_marks = list(set(marks))
unique_marks.sort()
print("Unique marks:", unique_marks)


subject_marks = {
    "Python": 85,
    "Excel": 90,
    "Power BI": 75
}


subject_marks["Python"] = 95


subject_marks["SQL"] = 88

print("\n--- Subject-wise Marks ---")
for subject, mark in subject_marks.items():
    print(f"{subject}: {mark}")


subjects = frozenset(["Python", "Excel", "SQL", "Power BI"])

