print(subjects)

online_students = {"Ebin", "Rahul", "Anu", "Arun"}
offline_students = {"Ebin", "Anu", "Manu", "Ravi"}

print("\n--- Student Registration ---")
print("Online Students:", online_students)
print("Offline Students:", offline_students)


print("Common students:", online_students & offline_students)


print("All students:", online_students | offline_students)


print("Only online students:", online_students - offline_students)


total = sum(subject_marks.values())
average = total / len(subject_marks)

print("\n--- Grade Calculation ---")
print(f"Total Marks: {total}")
print(f"Average Marks: {average:.2f}")

if average >= 90:
    grade = "A"
elif average >= 75:
    grade = "B"
elif average >= 50:
    grade = "C"
else:
    grade = "Fail"

print(f"Student Grade: {grade}")


